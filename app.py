库 = 建向量库(资料片段们)


def 算距离(向量a, 向量b):
    距离 = 0
    for i in range(min(len(向量a), len(向量b))):
        差值 = 向量a[i] - 向量b[i]
        距离 = 距离 + abs(差值)
    return 距离

def 搜库(问题,库):
    问题向量 = 真转向量(问题)
    最小距离 = 99999
    最像片段 = ""
    for 片段 in 库:
        片段向量 = 库[片段]
        距离 = 算距离(问题向量, 片段向量)
        if 距离 < 最小距离:
            最小距离 = 距离
            最像片段 = 片段
    return 最像片段



def 生成回答(问题, 最像片段):
    提示词 = f"根据下面这份资料回答用户问题，如果资料里没有答案，就说不知道。 \n\n资料: {最像片段}\n\n问题:{问题}"
    resp = requests.post("http://127.0.0.1:11434/api/generate",
                         json={"model":"qwen2.5:3b", "prompt": 提示词, "stream" : False})
    return resp.json()["response"]

问题 = st.text_input("请输入你的问题")
if st.button("提问"):
    最像片段 = 搜库(问题, 库)
    回答 = 生成回答(问题, 最像片段)
    st.write(回答)
    st.write("命中的资料：", 最像片段)