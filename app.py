import streamlit as st
import requests

st.title("企业知识库问答")


def 真转向量(文字):
    resp_out = requests.post("http://127.0.0.1:11434/api/embed",json={"model": "bge-m3", "input": 文字})
    data_out = resp_out.json()
    向量= data_out["embeddings"][0]
    return 向量

def 建向量库(片段们):
    库 = {}
    for 片段 in 片段们:
        库[片段] = 真转向量(片段)
    return 库

